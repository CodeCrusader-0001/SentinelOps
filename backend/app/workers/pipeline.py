import logging
from typing import List, Dict, Any
from backend.app.database.session import SessionLocal
from backend.app.models.log import Log
from backend.app.models.anomaly import Anomaly
from backend.app.models.incident import Incident
from backend.app.core.logging import logger

def run_pipeline_sync(log_ids: List[str]) -> Dict[str, Any]:
    """
    Executes synchronous end-to-end log processing pipeline:
    1. Loads logs
    2. Runs anomaly detection (DeepLog or rule-based fallback)
    3. Persists anomalies
    4. Auto-generates or correlates Incidents with deduplication
    """
    db = SessionLocal()
    processed_count = 0
    anomalies_detected = 0
    incidents_created = 0

    try:
        logs = db.query(Log).filter(Log.id.in_(log_ids)).all()
        if not logs:
            return {"status": "no_logs_found", "count": 0}

        # Dynamically import detector to avoid circular dependencies
        from backend.app.detection.service import anomaly_detection_service

        for log in logs:
            log.processing_status = "PROCESSING"
            db.commit()

            detection_result = anomaly_detection_service.evaluate_log(log)

            if detection_result.is_anomaly:
                anomalies_detected += 1
                log.processing_status = "ANOMALOUS"

                # Create Anomaly Record
                anomaly = Anomaly(
                    service=log.service,
                    anomaly_score=detection_result.anomaly_score,
                    actual_event=detection_result.actual_event,
                    predicted_events=detection_result.predicted_event,
                    detection_method=detection_result.detection_method,
                    supporting_evidence=detection_result.supporting_evidence,
                    details=detection_result.details
                )
                db.add(anomaly)
                db.commit()
                db.refresh(anomaly)

                # Determine Incident Severity
                severity = "HIGH"
                if log.level in ["CRITICAL"]:
                    severity = "CRITICAL"
                elif log.level in ["WARNING"]:
                    severity = "MEDIUM"

                # Deduplication key based on service and core failure signature
                dedup_sig = log.message.split(":")[0][:50].strip()
                dedup_key = f"auto-{log.service}-{dedup_sig}"

                # Auto-generate or Correlate Incident
                existing_incident = db.query(Incident).filter(
                    Incident.deduplication_key == dedup_key,
                    Incident.status.in_(["OPEN", "INVESTIGATING", "PENDING_APPROVAL", "REMEDIATING"])
                ).first()

                if existing_incident:
                    log.incident_id = existing_incident.id
                    anomaly.incident_id = existing_incident.id
                    existing_incident.description += f"\n[{log.timestamp}] {log.service}: {log.message}"
                else:
                    new_incident = Incident(
                        title=f"Anomaly Detected in {log.service}: {dedup_sig}",
                        description=f"Automated incident generated by {detection_result.detection_method}.\n"
                                    f"Initial Anomaly: {detection_result.supporting_evidence}\n"
                                    f"Log Message: {log.message}",
                        severity=severity,
                        status="OPEN",
                        source=f"Anomaly Detector ({detection_result.detection_method})",
                        deduplication_key=dedup_key
                    )
                    db.add(new_incident)
                    db.commit()
                    db.refresh(new_incident)
                    
                    log.incident_id = new_incident.id
                    anomaly.incident_id = new_incident.id
                    incidents_created += 1

                db.commit()
            else:
                log.processing_status = "PROCESSED"
                db.commit()

            processed_count += 1

        logger.info(
            f"Pipeline executed: {processed_count} logs, {anomalies_detected} anomalies, {incidents_created} incidents."
        )

        return {
            "status": "success",
            "processed": processed_count,
            "anomalies": anomalies_detected,
            "incidents": incidents_created
        }

    except Exception as e:
        logger.error(f"Error executing log processing pipeline: {str(e)}", exc_info=True)
        db.rollback()
        return {"status": "error", "error": str(e)}
    finally:
        db.close()

